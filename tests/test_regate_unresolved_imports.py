def test_report_artifact_records_the_verdict(tmp_path: Path) -> None:
    """The plan row declares `produces`, so the check must write that artifact.

    Every other row writes evidence; staleness tracking reads it. A row with an
    empty `produces` would be the only unverifiable one in the plan.
    """
    import json

    impl = _impl_with_app(tmp_path, _app_importing("ScrollLatchDriver"))
    report = tmp_path / "ref" / "unresolved-imports.json"
    proc = _run(impl, "--check", "--report", str(report))

    assert proc.returncode != 0, proc.stdout + proc.stderr
    assert report.is_file(), "the declared artifact must be written"
    data = json.loads(report.read_text(encoding="utf-8"))
    assert data["status"] == "fail"
    assert any("ScrollLatchDriver" in entry for entry in data["unresolvedImports"])


def test_report_artifact_records_a_clean_pass(tmp_path: Path) -> None:
    import json

    impl = _impl_with_app(
        tmp_path, "export default function App() { return <div>ok</div>; }\n"
    )
    report = tmp_path / "ref" / "unresolved-imports.json"
    proc = _run(impl, "--check", "--report", str(report))

    assert proc.returncode == 0, proc.stdout + proc.stderr
    data = json.loads(report.read_text(encoding="utf-8"))
    assert data["status"] == "pass"
    assert data["unresolvedImports"] == []


def test_wrapper_usage_is_never_left_with_a_missing_import(tmp_path: Path) -> None:
    """Removing an import out from under a surviving reference is worse than
    the dangling import it replaces.

    ScrollReveal is used as a WRAPPER (`<ScrollReveal><X /></ScrollReveal>`),
    which the self-closing mount strip does not match. Stripping only the
    import leaves an undefined identifier — still unbuildable, now for a
    reason nothing reports. When any reference survives, fail loudly instead.
    """
    impl = _impl_with_app(
        tmp_path,
        "import ScrollReveal from './lib/ScrollReveal';\n"
        "export default function App() {\n"
        "  return <ScrollReveal><section>x</section></ScrollReveal>;\n"
        "}\n",
    )
    proc = _run(impl)

    assert proc.returncode != 0, proc.stdout + proc.stderr
    app = (impl / "src" / "App.tsx").read_text(encoding="utf-8")
    assert "import ScrollReveal" in app, (
        "the import must be left intact when it cannot be removed safely"
    )
    assert "still referenced" in (proc.stdout + proc.stderr)


@pytest.mark.parametrize(
    ("label", "source"),
    [
        ("re-export", "export { Thing } from './missing-reexport';\n"),
        ("star-re-export", "export * from './missing-star';\n"),
        ("dynamic-import", "const f = () => import('./missing-dynamic');\n"),
        ("require", "const r = require('./missing-require');\n"),
    ],
)
def test_every_module_specifier_form_is_checked(
    tmp_path: Path, label: str, source: str
) -> None:
    """A re-export or a dynamic import breaks the build exactly like a static
    one, so scanning only `import ... from` leaves real holes.

    Measured before this was closed: of five specifier forms, only `import type`
    was caught — re-exports, star re-exports, dynamic import() and require()
    all passed a clean verdict while pointing at files that do not exist.
    """
    impl = _impl_with_app(tmp_path, source + "export default function App() { return null; }\n")
    proc = _run(impl, "--check")

    assert proc.returncode != 0, f"{label} must be checked\n{proc.stdout}{proc.stderr}"
    assert "missing-" in (proc.stdout + proc.stderr)


def test_resolvable_reexport_and_dynamic_import_pass(tmp_path: Path) -> None:
    """The widened scan must not start failing on specifiers that DO resolve."""
    impl = _impl_with_app(
        tmp_path,
        "export { Thing } from './lib/Thing';\n"
        "const f = () => import('./lib/Thing');\n"
        "export default function App() { return null; }\n",
    )
    (impl / "src" / "lib" / "Thing.tsx").write_text("export const Thing = 1;\n", encoding="utf-8")
    proc = _run(impl, "--check")
    assert proc.returncode == 0, proc.stdout + proc.stderr


def test_named_import_missing_from_resolved_module_fails_loudly(
    tmp_path: Path,
) -> None:
    """A module that RESOLVES can still lack the symbols asked of it.

    realfood-v4: MotionController imported ten scroll constants from
    `@/generated/motion-skeletons`, which emit-motion-skeletons.sh regenerates
    as `use*` hooks and has never exported a constant. The development compiler
    served HTTP 200 with import warnings, every binding was `undefined`, the
    first deref threw inside the effect, and every motion channel that controller
    owned was dead. The production build caught it later during type checking;
    this re-gate must fail earlier.
    """
    impl = _impl_with_app(
        tmp_path,
        "import { NAV_TOP_OUTPUT, useNavScrollStateMachine } from "
        "'@/generated/motion-skeletons';\n"
        "export default function App() { return <div>{NAV_TOP_OUTPUT}</div>; }\n",
    )
    (impl / "src" / "generated").mkdir(parents=True)
    (impl / "src" / "generated" / "motion-skeletons.ts").write_text(
        "export function useNavScrollStateMachine() { return 'hidden-at-top'; }\n",
        encoding="utf-8",
    )
    proc = _run(impl)

    assert proc.returncode == 3, proc.stdout + proc.stderr
    assert "NAV_TOP_OUTPUT" in proc.stderr
    assert "useNavScrollStateMachine" not in proc.stderr, (
        "the export that DOES exist must not be reported")


