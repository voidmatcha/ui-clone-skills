"""Post-emit re-gate: no emitted module may import a file that does not exist.

Every driver has TWO independent predicates — one in scaffold_to_jsx.py deciding
whether App.tsx imports it, one in emit_scroll_helpers.py deciding whether the
file is written. Whenever a pair disagrees the generated project does not
compile, and nothing in the pipeline noticed: a clean scaffold of a 35/35-PASS
reference failed with "Could not resolve ./lib/ScrollLatchDriver".

Mirroring each predicate does not scale — there are ~12 driver imports across
three emitters (Next `@/lib/...`, vite `./lib/...`, and a third alias form), so
every pair would have to be kept in sync forever. This re-gate instead checks
GROUND TRUTH after emission: does the imported file exist on disk?
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
REGATE = ROOT / "skills" / "visual-debug" / "scripts" / "lib" / "regate_unresolved_imports.py"

# Every driver name the scaffold can import, across all three stacks.
DRIVER_NAMES = [
    "ScrollReveal",
    "ScrollScrub",
    "SmoothScroll",
    "ScrollStateDriver",
    "ScrollClassToggleDriver",
    "HoverClassToggleDriver",
    "ScrollLatchDriver",
    "ScrollLinkedStyleDriver",
    "SwiperActivator",
    "VideoAutoplayKick",
    "StateRevealDriver",
    "IOClassRevealDriver",
]


def _run(impl: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(REGATE), str(impl), *args],
        capture_output=True,
        text=True,
        timeout=60,
    )


def _impl_with_app(tmp_path: Path, app_body: str) -> Path:
    impl = tmp_path / "impl"
    (impl / "src" / "lib").mkdir(parents=True)
    (impl / "src" / "App.tsx").write_text(app_body, encoding="utf-8")
    return impl


def _app_importing(name: str, spec_prefix: str = "./lib/") -> str:
    return (
        "// Auto-generated by skills/visual-debug/scripts/scaffold-to-jsx.sh.\n"
        f"import {name} from '{spec_prefix}{name}';\n"
        "\n"
        "export default function App() {\n"
        "  return (\n"
        "    <div>\n"
        f"      <{name} />\n"
        "      <section>kept</section>\n"
        "    </div>\n"
        "  );\n"
        "}\n"
    )


@pytest.mark.parametrize("name", DRIVER_NAMES)
def test_dangling_driver_import_is_stripped_for_every_driver(
    tmp_path: Path, name: str
) -> None:
    """Per-instance proof that the class is closed, not just the latch case.

    Each driver is exercised with its file absent — the state its own gate pair
    produces when the two predicates disagree. The re-gate must remove both the
    import and the mount, leaving a tree that compiles.
    """
    impl = _impl_with_app(tmp_path, _app_importing(name))
    proc = _run(impl)

    assert proc.returncode == 0, proc.stdout + proc.stderr
    app = (impl / "src" / "App.tsx").read_text(encoding="utf-8")
    assert f"import {name}" not in app, app
    assert f"<{name} />" not in app, app
    assert "<section>kept</section>" in app, "unrelated markup must survive"
    assert name in proc.stderr, "removals must be reported, never silent"


def test_alias_specifier_is_resolved_against_src(tmp_path: Path) -> None:
    """The Next stack emits `@/lib/X`, which resolves to <impl>/src/lib/X."""
    impl = _impl_with_app(tmp_path, _app_importing("ScrollScrub", "@/lib/"))
    proc = _run(impl)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert "import ScrollScrub" not in (impl / "src" / "App.tsx").read_text(encoding="utf-8")


def test_resolvable_import_is_left_alone(tmp_path: Path) -> None:
    """A driver whose file exists must not be touched."""
    impl = _impl_with_app(tmp_path, _app_importing("SmoothScroll"))
    (impl / "src" / "lib" / "SmoothScroll.tsx").write_text("export default () => null;\n")
    proc = _run(impl)

    assert proc.returncode == 0, proc.stdout + proc.stderr
    app = (impl / "src" / "App.tsx").read_text(encoding="utf-8")
    assert "import SmoothScroll" in app
    assert "<SmoothScroll />" in app


def test_unresolvable_non_driver_import_fails_loudly(tmp_path: Path) -> None:
    """A dangling import that is NOT a known driver is a real bug.

    Stripping it would hide a genuine emitter fault, so the gate fails instead.
    This is the missing build check: it is what should have caught the latch
    defect before a 35/35-PASS reference shipped a non-compiling tree.
    """
    impl = _impl_with_app(
        tmp_path,
        "import Hero from './components/Hero';\n"
        "export default function App() { return <Hero />; }\n",
    )
    proc = _run(impl)

    assert proc.returncode != 0, proc.stdout + proc.stderr
    assert "Hero" in (proc.stdout + proc.stderr)


def test_check_mode_reports_without_editing(tmp_path: Path) -> None:
    """--check is the verification-plan row: report, never mutate."""
    impl = _impl_with_app(tmp_path, _app_importing("ScrollLatchDriver"))
    before = (impl / "src" / "App.tsx").read_text(encoding="utf-8")
    proc = _run(impl, "--check")

    assert proc.returncode != 0, proc.stdout + proc.stderr
    assert (impl / "src" / "App.tsx").read_text(encoding="utf-8") == before


def test_clean_tree_passes(tmp_path: Path) -> None:
    impl = _impl_with_app(
        tmp_path,
        "export default function App() { return <div>ok</div>; }\n",
    )
    proc = _run(impl)
